CREATE TABLE IF NOT EXISTS USERS (
    ID SERIAL PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL,
    SURNAME VARCHAR(50) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PATIENTS (
    ID SERIAL PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL,
    SURNAME VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS EMERGENCIES (
    ID SERIAL PRIMARY KEY,
    P_ID INT NOT NULL,
    TYPE INT NOT NULL,
    BPM INT,
    RESOLVED BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    RESOLVED_AT TIMESTAMP WITH TIME ZONE,
    RESOLVED_BY INT,

    CONSTRAINT fk_emergency_patient
        FOREIGN KEY (P_ID) 
        REFERENCES PATIENTS(ID) 
        ON DELETE CASCADE ON UPDATE CASCADE,
    
    CONSTRAINT fk_emergency_user
        FOREIGN KEY (RESOLVED_BY) 
        REFERENCES USERS(ID) 
        ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS DEVICES (
    ID SERIAL PRIMARY KEY,
    MAC_ADDRESS MACADDR UNIQUE,
    NAME TEXT DEFAULT 'OPPO Watch',
    ONLINE BOOLEAN NOT NULL DEFAULT FALSE,
    STATUS VARCHAR(20) DEFAULT 'PENDING',
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PATIENT_DEVICE (
    ID SERIAL PRIMARY KEY,
    D_ID INT NOT NULL,
    P_ID INT NOT NULL,
    ASSIGNED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    IS_ACTIVE BOOLEAN DEFAULT TRUE,

    CONSTRAINT fk_patient
        FOREIGN KEY (P_ID) 
        REFERENCES PATIENTS(ID) 
        ON DELETE CASCADE ON UPDATE CASCADE,

    CONSTRAINT fk_device
        FOREIGN KEY (D_ID) 
        REFERENCES DEVICES(ID) 
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS push_subscriptions (
    id SERIAL PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint TEXT UNIQUE NOT NULL,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_push_subscriptions_id ON push_subscriptions (id);

CREATE INDEX idx_emergencies_active 
ON EMERGENCIES (P_ID, CREATED_AT DESC) 
WHERE RESOLVED = FALSE;

CREATE INDEX idx_emergencies_patient 
ON EMERGENCIES (P_ID);

CREATE INDEX idx_patient_devices_patient_id ON PATIENT_DEVICE(P_ID);
CREATE INDEX idx_patient_devices_device_id ON PATIENT_DEVICE(D_ID);

CREATE UNIQUE INDEX idx_unique_active_device 
ON PATIENT_DEVICE (D_ID) 
WHERE IS_ACTIVE = TRUE;

CREATE UNIQUE INDEX idx_unique_active_patient 
ON PATIENT_DEVICE (P_ID) 
WHERE IS_ACTIVE = TRUE;